"""M3-wide analysis: executor RL on synthetic plans with many independent subgoals (poset vs random-order chain).

Reads results/m3w/reeval.jsonl (checkpoints at steps 25, 50, 75, 100 and the base model, 16 samples per problem)
and state_{poset,chain_rand}.json (training accuracy at every RL step); writes numbers_m3w.tex, tab_m3w.tex and
figs/fig_m3w.pdf. Intervals: paired bootstrap over problems (20,000 resamples, seed 0).
"""
import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"; (OUT / "figs").mkdir(parents=True, exist_ok=True)  # generated figures and LaTeX tables
RES = Path(sys.argv[1]) if len(sys.argv) > 1 else next(
    p for p in [HERE.parent / "experiments" / "results" / "m3w", HERE.parent / "pohrl" / "experiments" / "results" / "m3w"] if p.exists())
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False, "pdf.fonttype": 42,
                     "axes.titlesize": 9})
C = {"base": "#555555", "chain_rand": "#8c4fb0", "poset": "#2a6fdb"}
LBL = {"base": "base model", "chain_rand": "chain credit, random order", "poset": "poset credit"}

R = {}
for line in open(RES / "reeval.jsonl"):
    r = json.loads(line); R[r["tag"]] = r["rows"]
pids = [x["pid"] for x in R["base@0"]]
assert all([x["pid"] for x in rows] == pids for rows in R.values())
K = np.array([x["width"] for x in R["base@0"]])  # width = number of independent parts
acc = lambda t: np.array([x["acc"] for x in R[t]])
words = lambda t: np.array([x["words_out"] for x in R[t]])
SETS = {"All": K > 0, "One": K == 1, "TwoThree": (K >= 2) & (K <= 3), "Four": K >= 4, "Wide": K >= 2}
rng = np.random.default_rng(0)


def ci(v):
    b = v[rng.integers(0, len(v), (20000, len(v)))].mean(1)
    return v.mean(), np.percentile(b, 2.5), np.percentile(b, 97.5)


N = {}
p = lambda x: f"{100 * x:.1f}"
pp = lambda x: f"${100 * x:+.1f}$"
N["MWNeval"], N["MWNone"], N["MWNtwothree"], N["MWNfour"] = (str(int(SETS[k].sum())) for k in ["All", "One", "TwoThree", "Four"])
for k, s in SETS.items():
    N[f"MWBase{k}"] = p(acc("base@0")[s].mean())
steps_name = {25: "XXV", 50: "L", 75: "LXXV", 100: "C"}
for st, nm in steps_name.items():
    for m, mn in [("poset", "Poset"), ("chain_rand", "Rand")]:
        for k, s in SETS.items():
            N[f"MW{mn}{nm}{k}"] = p(acc(f"{m}@{st}")[s].mean())
    d = acc(f"poset@{st}") - acc(f"chain_rand@{st}")
    for k, s in SETS.items():
        v, lo, hi = ci(d[s])
        N[f"MWDiff{nm}{k}"], N[f"MWDiff{nm}{k}Lo"], N[f"MWDiff{nm}{k}Hi"] = pp(v), pp(lo), pp(hi)

# training curves (same problems at every step for both methods)
T = {}
for m in ["poset", "chain_rand"]:
    L = sorted([r for r in json.load(open(RES / f"state_{m}.json"))["log"] if "train_acc" in r and r["step"] > 0],
               key=lambda r: r["step"])
    T[m] = np.array([r["train_acc"] for r in L])
ma = {m: np.convolve(v, np.ones(5) / 5, "valid") for m, v in T.items()}
first = lambda v, thr: int(np.argmax(v >= thr)) + 5
for m, mn in [("poset", "Poset"), ("chain_rand", "Rand")]:
    N[f"MWReachEighty{mn}"], N[f"MWReachNinety{mn}"] = str(first(ma[m], 0.8)), str(first(ma[m], 0.9))
for lo, hi, nm in [(1, 25, "A"), (26, 50, "B"), (51, 100, "C")]:
    dd = T["poset"][lo - 1:hi] - T["chain_rand"][lo - 1:hi]
    N[f"MWTrain{nm}Poset"], N[f"MWTrain{nm}Rand"] = p(T["poset"][lo - 1:hi].mean()), p(T["chain_rand"][lo - 1:hi].mean())
    N[f"MWTrain{nm}Diff"] = pp(dd.mean())
for m, mn in [("poset", "Poset"), ("chain_rand", "Rand")]:
    N[f"MWWords{mn}C"] = f"{words(f'{m}@100').mean():.0f}"
N["MWWordsBase"] = f"{words('base@0').mean():.0f}"

with open(OUT / "numbers_m3w.tex", "w") as f:
    f.write("% generated by m3w_analysis.py\n")
    for k, v in N.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


def cell(v):
    return f"{100 * v:.1f}"


def dcell(d, s):
    v, lo, hi = ci(d[s])
    return f"${100 * v:+.1f}$ {{\\scriptsize$[{100 * lo:+.1f}, {100 * hi:+.1f}]$}}"


rows = [f"base model & --- & " + " & ".join(cell(acc('base@0')[SETS[k]].mean()) for k in ["All", "One", "TwoThree", "Four"]) + r" \\", r"\midrule"]
for st in (25, 50, 75, 100):
    for m in ["poset", "chain_rand"]:
        rows.append(f"{LBL[m]} & {st} & " + " & ".join(cell(acc(f'{m}@{st}')[SETS[k]].mean()) for k in ["All", "One", "TwoThree", "Four"]) + r" \\")
    d = acc(f"poset@{st}") - acc(f"chain_rand@{st}")
    rows.append(r"\quad difference & " + f"{st} & " + " & ".join(dcell(d, SETS[k]) for k in ["All", "One", "TwoThree", "Four"]) + r" \\")
    if st != 100:
        rows.append(r"\addlinespace")
tab = r"""\begin{table}[!htbp]
\centering\small
\caption{M3 on plans with many independent subgoals (Qwen3-1.7B, LoRA, one seed per method, gold step verification): accuracy (\%%) by number of independent parts $k$, evaluated with 16 samples per problem at four checkpoints. Single-part problems ($k=1$, a chain) are the control. Difference: poset minus random-order chain credit, in points, with 95\%% paired bootstrap intervals over problems.}\label{tab:m3w}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{lccccc}
\toprule
 & RL step & all ($n=%s$) & $k=1$ ($%s$) & $k=2$--$3$ ($%s$) & $k=4$--$6$ ($%s$)\\
\midrule
%s
\bottomrule
\end{tabular}}
\end{table}
""" % (N["MWNeval"], N["MWNone"], N["MWNtwothree"], N["MWNfour"], "\n".join(rows))
(OUT / "tab_m3w.tex").write_text(tab)

fig, ax = plt.subplots(1, 2, figsize=(10, 3.2), gridspec_kw={"width_ratios": [1, 1.2]})
ks = np.arange(1, 7)
for m, tag, mk in [("base", "base@0", "s"), ("chain_rand", "chain_rand@25", "o"), ("poset", "poset@25", "o")]:
    a = acc(tag)
    ax[0].plot(ks, [100 * a[K == k].mean() for k in ks], marker=mk, color=C[m], label=LBL[m] + ("" if m == "base" else ", step 25"))
ax[0].set_xlabel("number of independent parts $k$"); ax[0].set_ylabel("accuracy (%)"); ax[0].set_ylim(0, 100)
ax[0].set_title("(a) accuracy after 25 RL steps, by plan width"); ax[0].legend(frameon=False, fontsize=7.5)
for m in ["chain_rand", "poset"]:
    ax[1].plot(np.arange(1, len(T[m]) + 1), 100 * T[m], color=C[m], alpha=0.25, lw=0.8)
    ax[1].plot(np.arange(5, len(T[m]) + 1), 100 * ma[m], color=C[m], lw=1.6, label=LBL[m])
ax[1].axhline(90, color="k", ls=":", lw=0.7)
ax[1].set_xlabel("RL step"); ax[1].set_ylabel("training accuracy (%)"); ax[1].set_ylim(0, 100)
ax[1].set_title("(b) training accuracy (5-step moving average)"); ax[1].legend(frameon=False, fontsize=7.5, loc="lower right")
plt.tight_layout(); plt.savefig(OUT / "figs" / "fig_m3w.pdf"); plt.savefig(OUT / "figs" / "fig_m3w.png", dpi=150)
print(json.dumps({k: N[k] for k in ["MWDiffXXVAll", "MWDiffXXVOne", "MWDiffXXVTwoThree", "MWDiffXXVFour", "MWReachNinetyPoset", "MWReachNinetyRand"]}))
